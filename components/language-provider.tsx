const Context=createContext<{language:Language;setLanguage:(lang:Language)=>void;tr:(s:string)=>string}>({language:'en',setLanguage:()=>{},tr:s=>s})
export function LanguageProvider({children}:{children:ReactNode}) {
  const [language,setLanguage]=useState<Language>('en')
  useEffect(()=>{try {const saved=localStorage.getItem('biscuitflow-language');if(saved==='en'||saved==='zh')setLanguage(saved)}catch{}},[])
  useEffect(()=>{try{localStorage.setItem('biscuitflow-language',language)}catch{};document.documentElement.lang=language==='zh'?'zh-CN':'en'},[language])
  return <Context.Provider value={{language,setLanguage,tr:(s)=>language==='zh'?(chinese[s]??s):s}}>{children}</Context.Provider>
}
export const useLanguage=()=>useContext(Context)
